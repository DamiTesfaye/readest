const BookmarksNotesArt: React.FC<MoreArtProps> = ({ colored, hovered, openDelayMs }) => {
  const { animating, onAnimationIteration } = useMoreArtMotion(hovered, openDelayMs);
  const origins = colored ? ART.colored : ART.muted;
  const still = (origin: string): CSSProperties => ({
    transformBox: 'view-box',
    transformOrigin: origin,
  });
  const ribbonStyle = (part: NotesPart): CSSProperties =>
    animating
      ? ({
          ...playStyle('more-notes-flick', CYCLE_S, origins.ribbons[part]),
          '--more-notes-tilt': TILTS[part],
        } as CSSProperties)
      : still(origins.ribbons[part]);

  return (
    <svg
      width={colored ? '21' : '16'}
      height={colored ? '32' : '25'}
      viewBox={colored ? '0 0 21 32' : '0 0 16 25'}
      fill='none'
      xmlns='http://www.w3.org/2000/svg'
      aria-hidden='true'
      data-testid='more-art-bookmarks-notes'
      data-animating={animating}
      className='h-7 w-auto overflow-visible'
      onAnimationIteration={onAnimationIteration}
    >
      <style>{KEYFRAMES}</style>
      <g
        data-part='book'
        style={
          animating ? playStyle('more-notes-rock', CYCLE_S, origins.book) : still(origins.book)
        }
      >
        {renderSegments(colored ? COLORED_SEGMENTS : MUTED_SEGMENTS, ribbonStyle)}
      </g>
    </svg>
  );
};

export default BookmarksNotesArt;
